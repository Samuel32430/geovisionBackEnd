ADD CONSTRAINT VENTA_paciente_fk FOREIGN KEY (id_paciente) REFERENCES PACIENTE(id_persona)
ADD CONSTRAINT VENTA_receta_fk FOREIGN KEY (id_receta) REFERENCES RECETA(id_receta);

ALTER TABLE PAGO
